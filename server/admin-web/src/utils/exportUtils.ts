// ─── CSV export ───────────────────────────────────────────────────────────────

/** Convert an array of flat objects to a CSV string and trigger a download. */
export function downloadCSV(filename: string, rows: Record<string, unknown>[]) {
  if (rows.length === 0) return;
  const headers = Object.keys(rows[0]);
  const escape = (v: unknown) => {
    const s = v == null ? '' : String(v);
    return s.includes(',') || s.includes('"') || s.includes('\n')
      ? `"${s.replace(/"/g, '""')}"`
      : s;
  };
  const csv = [
    headers.join(','),
    ...rows.map(r => headers.map(h => escape(r[h])).join(',')),
  ].join('\r\n');
  triggerDownload(`${filename}.csv`, 'text/csv;charset=utf-8;', csv);
}

// ─── Print-to-PDF ─────────────────────────────────────────────────────────────

/** Open a minimal styled print window and trigger browser Print → Save as PDF. */
export function printReport(title: string, html: string) {
  const win = window.open('', '_blank');
  if (!win) return;
  win.document.write(`<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <title>${title}</title>
  <style>
    * { box-sizing: border-box; margin: 0; padding: 0; }
    body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif; font-size: 11px; color: #111; padding: 24px 32px; }
    h1 { font-size: 20px; font-weight: 700; margin-bottom: 4px; }
    .meta { font-size: 10px; color: #666; margin-bottom: 20px; }
    table { width: 100%; border-collapse: collapse; margin-top: 12px; }
    th { background: #f0f4f8; text-align: left; padding: 6px 8px; font-size: 10px; text-transform: uppercase; letter-spacing: .04em; color: #444; border-bottom: 2px solid #d1dbe6; }
    td { padding: 5px 8px; border-bottom: 1px solid #e8eef4; vertical-align: top; }
    tr:nth-child(even) td { background: #f9fbfd; }
    .badge { display: inline-block; padding: 1px 6px; border-radius: 999px; font-size: 10px; font-weight: 600; }
    .badge-green { background: #d1fae5; color: #065f46; }
    .badge-red   { background: #fee2e2; color: #991b1b; }
    .badge-amber { background: #fef3c7; color: #92400e; }
    .badge-gray  { background: #f1f5f9; color: #475569; }
    @media print { body { padding: 0; } }
  </style>
</head>
<body>
  <h1>${title}</h1>
  <div class="meta">Generated by SeceoKnight MDM &mdash; ${new Date().toLocaleString()}</div>
  ${html}
  <script>window.onload = () => { window.print(); }</script>
</body>
</html>`);
  win.document.close();
}

// ─── Helpers ──────────────────────────────────────────────────────────────────

function triggerDownload(filename: string, mime: string, content: string) {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url; a.download = filename; a.click();
  setTimeout(() => URL.revokeObjectURL(url), 5000);
}
